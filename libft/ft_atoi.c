#include "libft.h"

int	ft_atoi(const char *s)
{
	int	sign;
	int	n;

	sign = 1;
	n = 0;
	while (((*s >= 9 && *s <= 13) || *s == 32) && *s++)
		;
	if (*s++ == '-')
		sign *= -1;
	while (*s >= '0' && *s <= '9')
		n = n * 10 + *s++ - '0';
	n *= sign;
	return (n);
}
